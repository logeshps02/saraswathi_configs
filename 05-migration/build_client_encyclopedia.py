def banner(status, reason):
    """Only mark features that are missing or limited. Live features have no badge."""
    if status == "off":
        return (
            "\n> **Not configured on this firm.** Do not look for this button today.\n"
            f"> {reason}\n"
        )
    if status == "partial":
        return (
            "\n> **Limit on this firm.** "
            f"{reason}\n"
        )
    return ""


def md_escape_table(s):
    return s.replace("\n", "<br>").replace("|", "\\|")


def problem_rows(problems):
    rows = []
    for block in problems.split("\n"):
        block = block.strip()
        if not block or block.lower().startswith("none"):
            continue
        if "→" not in block:
            continue
        left, right = block.split("→", 1)
        rows.append((left.strip(), right.strip()))
    return rows


